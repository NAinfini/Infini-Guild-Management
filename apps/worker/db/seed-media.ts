async function deleteKeys(bucket: R2Bucket, keys: readonly string[]): Promise<void> {
  for (let index = 0; index < keys.length; index += 1_000) {
    await bucket.delete(keys.slice(index, index + 1_000));
  }
}

export async function clearLocalMediaObjects(env: Bindings): Promise<void> {
  if (env.ENVIRONMENT !== "development") {
    throw new Error("Local media cleanup is available only in development");
  }

  const keys: string[] = [];
  let cursor: string | undefined;
  do {
    const page = await env.MEDIA.list({
      prefix: "media/",
      limit: 1_000,
      ...(cursor ? { cursor } : {}),
    });
    keys.push(...page.objects.map((object) => object.key));
    cursor = page.truncated ? page.cursor : undefined;
  } while (cursor);

  if (keys.length > 0) await deleteKeys(env.MEDIA, keys);
}

