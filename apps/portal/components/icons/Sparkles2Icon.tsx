import type { Variants } from "motion/react";
import { motion, useAnimation } from "motion/react";
import type { HTMLAttributes } from "react";
import { forwardRef, useCallback, useImperativeHandle, useRef } from "react";
import { cn } from "@portal/utils/cn";
import { useParentInteractiveHover } from "./useParentInteractiveHover";

export interface Sparkles2IconHandle {
  startAnimation: () => void;
  stopAnimation: () => void;
}

interface Sparkles2IconProps extends HTMLAttributes<HTMLDivElement> {
  size?: number;
}

const SMALL_STAR_VARIANTS: Variants = {
  normal: { scale: 1, rotate: 0, transition: { duration: 0.3 } },
  animate: {
    scale: [1, 1.3, 0.8, 1.1, 1],
    rotate: [0, 15, -10, 0],
    transition: { duration: 0.6, ease: "easeInOut" },
  },
};

const BIG_STAR_VARIANTS: Variants = {
  normal: { scale: 1, rotate: 0, transition: { duration: 0.3 } },
  animate: {
    scale: [1, 1.15, 0.9, 1.05, 1],
    rotate: [0, -10, 5, 0],
    transition: { duration: 0.6, ease: "easeInOut", delay: 0.1 },
  },
};

const Sparkles2Icon = forwardRef<Sparkles2IconHandle, Sparkles2IconProps>(
  ({ onMouseEnter, onMouseLeave, className, size = 28, ...props }, ref) => {
    const controls = useAnimation();
    const isControlledRef = useRef(false);
    const wrapperRef = useParentInteractiveHover(controls, isControlledRef);

    useImperativeHandle(ref, () => {
      isControlledRef.current = true;
      return {
        startAnimation: () => controls.start("animate"),
        stopAnimation: () => controls.start("normal"),
      };
    });

    const handleMouseEnter = useCallback(
      (e: React.MouseEvent<HTMLDivElement>) => {
        if (isControlledRef.current) { onMouseEnter?.(e); } else { controls.start("animate"); }
      },
      [controls, onMouseEnter],
    );

    const handleMouseLeave = useCallback(
      (e: React.MouseEvent<HTMLDivElement>) => {
        if (isControlledRef.current) { onMouseLeave?.(e); } else { controls.start("normal"); }
      },
      [controls, onMouseLeave],
    );

    return (
      <div ref={wrapperRef} className={cn(className)} onMouseEnter={handleMouseEnter} onMouseLeave={handleMouseLeave} {...props}>
        <svg fill="none" height={size} stroke="currentColor" strokeLinecap="round" strokeLinejoin="round" strokeWidth="2" viewBox="0 0 24 24" width={size} xmlns="http://www.w3.org/2000/svg">
          <motion.path animate={controls} initial="normal" variants={SMALL_STAR_VARIANTS} style={{ transformOrigin: "17px 7px" }} d="M13 7a9.3 9.3 0 0 0 1.516 -.546c.911 -.438 1.494 -1.015 1.937 -1.932c.207 -.428 .382 -.928 .547 -1.522c.165 .595 .34 1.095 .547 1.521c.443 .918 1.026 1.495 1.937 1.933c.426 .205 .925 .38 1.516 .546a9.3 9.3 0 0 0 -1.516 .547c-.911 .438 -1.494 1.015 -1.937 1.932a9 9 0 0 0 -.547 1.521c-.165 -.594 -.34 -1.095 -.547 -1.521c-.443 -.918 -1.026 -1.494 -1.937 -1.932a9 9 0 0 0 -1.516 -.547" />
          <motion.path animate={controls} initial="normal" variants={BIG_STAR_VARIANTS} style={{ transformOrigin: "10px 14px" }} d="M3 14a21 21 0 0 0 1.652 -.532c2.542 -.953 3.853 -2.238 4.816 -4.806a20 20 0 0 0 .532 -1.662a20 20 0 0 0 .532 1.662c.963 2.567 2.275 3.853 4.816 4.806q .75 .28 1.652 .532a21 21 0 0 0 -1.652 .532c-2.542 .953 -3.854 2.238 -4.816 4.806a20 20 0 0 0 -.532 1.662a20 20 0 0 0 -.532 -1.662c-.963 -2.568 -2.275 -3.853 -4.816 -4.806a21 21 0 0 0 -1.652 -.532" />
        </svg>
      </div>
    );
  },
);

Sparkles2Icon.displayName = "Sparkles2Icon";

export { Sparkles2Icon };
